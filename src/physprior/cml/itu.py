def k_alpha(f_ghz, pol: str = "V") -> tuple[np.ndarray, np.ndarray]:
    """k [dB/km/(mm/h)^alpha] and alpha at frequency f (GHz), pol "H" or "V"."""
    f = np.asarray(f_ghz, float)
    if np.any((f < 1) | (f > 100)):
        raise ValueError("P.838-3 covers 1-100 GHz")
    p = pol.upper()[0]
    if p not in "HV":
        raise ValueError(f"polarisation must be H or V, got {pol!r}")
    k_tab, a_tab = (K_H, ALPHA_H) if p == "H" else (K_V, ALPHA_V)
    lf = np.log10(f)
    lt = np.log10(F_GHZ)
    k = 10 ** np.interp(lf, lt, np.log10(k_tab))
    alpha = np.interp(lf, lt, a_tab)
    return k, alpha
